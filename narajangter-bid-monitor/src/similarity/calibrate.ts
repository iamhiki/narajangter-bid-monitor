import type { SimilarityBasis } from "./index.js";

/**
 * 원점수를 사람이 읽는 싱크로율(%)로 바꾼다.
 *
 * **왜 필요한가.** 원점수는 코사인·포함도 값이라 "얼마나 같은가"의 비율이 아니다.
 * 실측하면 사업명이 100% 일치해도 최종 0.80이 천장이고, 같은 업무·다른 현장이 0.50,
 * 무관 공고가 0.12다. 이걸 그대로 "싱크로율 50%"로 보여주면 "절반이 같다"로 읽히는데
 * 실제 뜻은 "같은 종류의 일"이다. 팀장이 기대한 감각(강한 일치 = 90%대)과도 어긋난다.
 *
 * **눈금의 뜻 (2026-10-14 다시 잡음).** 담당자는 싱크로율을 "몇 % 같은 일인가"로 읽는다. 그래서 지일 과거
 * 실적끼리 비교한 가운데 값(같은 종류의 일·다른 현장)을 70%, 그 90분위를 88%에 둔다. 50%("절반쯤 겹친다")는
 * 경계선이 시작하는 자리다. 이전 눈금은 지일 실적 가운데 값을 50%에 둬서, 같은 종류의 일도 "절반만 같다"로
 * 읽혀 너무 낮다는 지적을 받았다. 대응점의 원점수(실측 분위)는 그대로이고 표시값만 옮겼다 — 순서는 같다.
 *
 * **왜 안전한가.** 이 변환은 **단조 증가**다. 원점수 순서를 하나도 바꾸지 않으므로
 * 순위·판별력이 전혀 달라지지 않는다. 눈금만 바꾼다. 점수를 올리려고 포화계수 k나
 * 가중치를 건드리는 것과는 다르다 — 그건 분리도를 실제로 망가뜨린다(측정으로 확인).
 *
 * **왜 기준별로 다른 곡선인가.** 제목만 본 점수와 과업지시서까지 읽은 점수는 분포가
 * 완전히 다르다(아래 실측표). 한 곡선으로 누르면 한쪽이 반드시 틀어진다. 기준별로
 * 보정하면 **두 기준의 값을 같은 잣대로 읽을 수 있게 되는** 부수 효과도 생긴다.
 */

/** 원점수 → 표시값(0~1) 대응점. x는 오름차순이어야 한다. */
interface AnchorCurve {
  points: { raw: number; shown: number }[];
}

/**
 * 기준 1 — 공고 제목만 보고 낸 점수 (첨부에서 과업 내용을 못 읽은 경우).
 *
 * 실측 분포 (2026-10-14, 실적 키워드 80% + 글자 비교 20% — keywordScore.ts. 비교 대상은 과업지시서가 있는 과거사업
 * 151건뿐(loadCorpus.ts), 과거사업 쪽 키워드는 지시서 앞 20,000자에서 센다. 질의는 제목만):
 *   지일 과거사업 151건 — 사업명으로 자기를 빼고 1위   15% 0.019 · 중앙 0.138 · 75% 0.202 · 90% 0.247 · 최고 0.392
 *   무관 공고 130건 (하수관로·도로·배관 등)           중앙 0.007 · 90% 0.046 · 최고 0.186
 *   헷갈리는 비대상 52건 (박물관 창호교체·놀이터 정비 등) 중앙 0.040 · 92% 0.203 · 최고 0.206
 * 경계: 0.21 → 80% (높음) 0.20에서 지일 26%·헷갈리는 비대상 12%, 0.25에서 지일 9%·헷갈리는 비대상 0% 사이.
 *       0.11 → 50% (경계선) 0.10에서 지일 58%·헷갈리는 비대상 25%, 0.15에서 40%·17% 사이. 무관은 둘 다 1% 이하.
 * 제목만으로는 정보가 적어 지일 일도 40% 넘게 경계선 아래로 내려가고, 헷갈리는 비대상도 넷 중 하나는 경계선에 든다 —
 * 과업지시서를 읽은 점수보다 덜 믿을 값이다.
 *
 * 이전 곡선(2026-09-22, 글자 조각만)은 헷갈리는 비대상과 지일 일을 거의 못 갈랐다(AUC 0.47 → 지금 0.69).
 */
const TITLE_CURVE: AnchorCurve = {
  points: [
    { raw: 0.0, shown: 0.0 },
    { raw: 0.046, shown: 0.15 }, // 무관 90분위 → 15%
    { raw: 0.11, shown: 0.5 }, // 경계선 시작 → 50%
    { raw: 0.138, shown: 0.7 }, // 지일 과거사업 중앙 → 70%
    { raw: 0.21, shown: 0.8 }, // 높음 시작 → 80%
    { raw: 0.247, shown: 0.88 }, // 지일 과거사업 90분위
    { raw: 0.39, shown: 0.95 },
    { raw: 0.7, shown: 0.98 },
    { raw: 1.0, shown: 1.0 },
  ],
};

/**
 * 기준 2 — 공고 첨부 과업지시서까지 읽고 낸 점수.
 *
 * 실측 분포 (2026-10-14, 실적 키워드 80% + 글자 비교 20%. 글자 비교는 앞 12,000자, 실적 키워드는 양쪽 지시서 앞 20,000자):
 *   지일 과거사업 151건 — 자기를 빼고 1위             15% 0.392 · 중앙 0.501 · 75% 0.580 · 90% 0.633 · 최고 0.865
 *   무관 공고 130건                                  중앙 0.034 · 90% 0.215 · 최고 0.397
 *   헷갈리는 비대상 52건                              중앙 0.103 · 92% 0.262 · 최고 0.355 (유아숲체험원 정비)
 * 경계: 0.565 → 80% (높음) 지일 30%가 넘고 무관·헷갈리는 비대상은 0%.
 *       0.37 → 50% (경계선) 지일 87%가 넘고 무관 1%, 헷갈리는 비대상 2%.
 * 헷갈리는 비대상은 직접 고른 표본이 아니라 제목·제외 키워드로 모은 것이라 지일 일에 가까운 것이 일부 섞여 있다
 * (유아숲체험원·놀이터 정비). 담당자 참가/불참 기록이 쌓이면 그걸로 다시 잡는다.
 *
 * 이전 곡선(2026-09-30, 글자 조각만)에서는 지일 일과 헷갈리는 비대상이 AUC 0.57로 거의 섞여 있었다(지금 0.98).
 */
const BODY_CURVE: AnchorCurve = {
  points: [
    { raw: 0.0, shown: 0.0 },
    { raw: 0.034, shown: 0.05 }, // 무관 공고 중앙 → 5%
    { raw: 0.37, shown: 0.5 }, // 경계선 시작 → 50%
    { raw: 0.501, shown: 0.7 }, // 지일 과거사업 중앙 → 70%
    { raw: 0.565, shown: 0.8 }, // 높음 시작 → 80%
    { raw: 0.633, shown: 0.88 }, // 지일 과거사업 90분위
    { raw: 0.865, shown: 0.97 },
    { raw: 1.0, shown: 1.0 }, // 같은 문서 → 100%
  ],
};

function interpolate(curve: AnchorCurve, raw: number): number {
  const pts = curve.points;
  if (raw <= pts[0]!.raw) return pts[0]!.shown;
  const last = pts[pts.length - 1]!;
  if (raw >= last.raw) return last.shown;

  for (let i = 1; i < pts.length; i++) {
    const hi = pts[i]!;
    if (raw > hi.raw) continue;
    const lo = pts[i - 1]!;
    const span = hi.raw - lo.raw;
    // 구간 폭이 0이면 나눗셈이 깨진다. 대응점을 잘못 넣었을 때의 방어.
    if (span <= 0) return hi.shown;
    const t = (raw - lo.raw) / span;
    return lo.shown + t * (hi.shown - lo.shown);
  }
  return last.shown;
}

/** 원점수를 표시용 싱크로율(0~1)로 바꾼다. */
export function calibrate(raw: number, basis: SimilarityBasis): number {
  if (!Number.isFinite(raw) || raw <= 0) return 0;
  return interpolate(basis === "제목+과업내용" ? BODY_CURVE : TITLE_CURVE, raw);
}

/** 화면·시트에 쓰는 정수 퍼센트. */
export function calibratedPercent(raw: number, basis: SimilarityBasis): number {
  return Math.round(calibrate(raw, basis) * 100);
}

/**
 * 표시값 기준 구간. 두 기준 모두 2026-10-13 실측 분포(지일 과거사업 vs 비대상 공고)로 맞췄다 —
 * 본문 기준은 원점수 0.565/0.37, 제목 기준은 0.21/0.11이 여기 온다 (각 곡선 주석).
 *
 * 실측의 "지일 일"은 과거 수행사업이지 담당자가 참가하기로 한 공고가 아니다 — 참가/불참 기록이
 * 쌓이면 그 기록으로 이 경계를 다시 잡는다.
 */
export const HIGH_BAND = 0.8;
export const LOW_BAND = 0.5;

export type SyncBand = "높음" | "경계선" | "낮음";

export function bandOf(shown: number): SyncBand {
  if (shown >= HIGH_BAND) return "높음";
  if (shown >= LOW_BAND) return "경계선";
  return "낮음";
}
