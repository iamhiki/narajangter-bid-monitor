import { describe, expect, it } from "vitest";
import { findSubmissionDeadline } from "../src/matching/submissionDeadline.js";

// 문구는 2026-10-02 개찰일로 마감을 대신한 공고 25건의 공고문에서 발췌했다
const at = (text: string) => findSubmissionDeadline(text)?.at ?? null;

describe("findSubmissionDeadline", () => {
  it("제출 일시 범위의 끝 시각을 마감으로 읽는다", () => {
    expect(at("8. 참가신청 및 제안서 제출 1) 제출일시 : 2026. 9. 22.(화) 10:00 ~ 17:00 ※ 지정된 시간 이후에는 접수하지 않음")).toBe(
      "2026-09-22 17:00"
    );
    expect(at("2) 제안서 접수 가. 제출일시: 2026. 10. 1.(목) 10:00~12:00, 13:00~15:00 (마감시간 이후 접수 불가)")).toBe("2026-10-01 15:00");
  });

  it("점심시간·평가위원 추첨 같은 괄호 속 시간은 마감이 아니다", () => {
    expect(at("제안서 접수 2026. 9. 9. (수) 10:00 ~ 17:00 (12:00 ~ 13:00 제외) • 방문접수에 한함")).toBe("2026-09-09 17:00");
    expect(at("입찰참가등록 및 제안서 제출 제 출 일 시 제출장소 제출방법 2026. 10. 13.(화) 13:00 ~ 17:00 (평가위원추첨 17:00~17:30)")).toBe(
      "2026-10-13 17:00"
    );
  });

  it("끝 날짜가 따로 있으면 그 날짜·시각", () => {
    expect(at("질의답변 2026. 9. 2.(수) 시 홈페이지 게시 제안서 접수 2026. 9. 4.(금) 09:00 ~ 2026. 9. 7.(월) 18:00까지")).toBe("2026-09-07 18:00");
    expect(at("5) 제안서 접수 : 2026. 10. 22.(목)(09:00 ~ 17:00) 6) 제안서 평가 : 2026. 10. 27.(화)(14:00 ~ 18:00)")).toBe("2026-10-22 17:00");
  });

  it("공고기간·질의접수·평가 일정, 공고일은 제출 마감으로 읽지 않는다", () => {
    expect(at("6. 입찰공고 및 제안서 제출 가. 입찰공고 - 공고기간 : 2026. 8. 6.(목) ~ 8. 22.(토)")).toBeNull();
    expect(at("제안서 제출 안내사항 등을 아래와 같이 공고합니다. 2026년 8월 26일 강 진 군 수")).toBeNull();
    expect(at("4. 입찰참가 신청 및 제안서 접수 가. 입찰공고 : 2026. 9. 16. ~ 10. 15. 나. 질의접수 및 회신 1) 접수일시 : 2026. 9. 16. ~ 2026. 9. 22. 18:00")).toBeNull();
  });

  it("제출처·전화번호가 끼어 멀어진 '제출기한'도 읽고, 질의 접수일시는 읽지 않는다 (태조왕건 동상)", () => {
    const text =
      "4. 입찰참가 신청 및 제안서 접수 가. 입찰공고 : 2026. 9. 16. ~ 10. 15. 나. 질의접수 및 회신 1) 접수일시 : 2026. 9. 16. ~ 2026. 9. 22. 18:00 " +
      "(제안요청서 내 <서식 1>, *마감시간 이후 접수 불가) 3) 질의회신 : 2026. 9. 24. 限 다. 가격제안서(입찰서) 제출 : 직접방문 접수(우편, 이메일 및 팩스 접수 불가) " +
      "1) 제 출 처 : 천안시청 11층 관광과 관광정책팀(☏041-521-5158) 2) 제출기한 : 2026. 10. 15. 14:00~17:00 라. 접수방법";
    expect(findSubmissionDeadline(text)).toMatchObject({ at: "2026-10-15 17:00", period: "2026. 10. 15. 14:00~17:00", conflict: false });
  });

  it("접수 '개시' 일시는 마감이 아니다 — 마감일시 쪽을 읽는다", () => {
    expect(at("입찰서 제출 개시 일시 : 2026. 9. 15.(화) 09:00 나. 전자 입찰서 제출 마감 일시 : 2026. 9. 22.(화) 12:00")).toBe("2026-09-22 12:00");
    expect(at("제안서ㆍ가격 전자입찰서접수개시일자 : 2026/09/23 10:00 제안서ㆍ가격 전자입찰서접수마감일시 : 2026/09/29 10:00")).toBe(
      "2026-09-29 10:00"
    );
  });

  it("기간 끝 날짜의 연도·월이 생략돼도 끝 날짜로 읽는다", () => {
    expect(at("입찰서 제출 기간 : 2026. 9. 18.(금) 15:00 ~ 10. 13.(화) 10:00")).toBe("2026-10-13 10:00");
    expect(at("제안서 제출 : 2026. 8. 10. 부터 2026. 8. 21. 10:00 까지")).toBe("2026-08-21 10:00");
    expect(at("제안서제출 전자 2026/09/01 10:00:00 2026/09/03 10:00:00")).toBe("2026-09-03 10:00");
  });

  it("공동수급협정서 제출기한, 띄어 쓴 '개 찰 일 시'는 제출 마감이 아니다", () => {
    expect(at("제안서 제출서류 … 8. 기타 제출서류 가. 공동수급협정서 : 공동계약으로 참여하는 경우에 한함 1) 제출기한 : 2026. 9. 1.(화) 18:00까지")).toBeNull();
    expect(at("입찰서접수 마감일시 2026. 08. 24. 10:00 부 가 가 치 세 금24,912,272원 개 찰 일 시 2026. 08. 24. 11:00")).toBe("2026-08-24 10:00");
  });

  it("공고문 안에 제출 날짜가 둘이면 이른 쪽을 쓰고 표시한다 (제주목 관아 — 10. 6.과 10. 2.)", () => {
    const r = findSubmissionDeadline(
      "※ 입찰참가등록 및 제안서 제출일시: 2026. 10. 6.(화) 09:00 ~ 17:00 (12:00~13:00 제외) … 7. 입찰참가 신청 및 제안서 제출 가. 제출일시: 2026. 10. 2.(금) 09:00 ~ 17:00 ※ 17:00이내 도착분에 한함"
    );
    expect(r).toMatchObject({ at: "2026-10-02 17:00", conflict: true });
  });
});
